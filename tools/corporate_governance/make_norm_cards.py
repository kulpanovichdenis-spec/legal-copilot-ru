# Текст блока проверки нормы определён в gov_cards.POLICY_BLOCK_LINES (валидатор требует его без изменений).
POLICY = "\n".join(cards.POLICY_BLOCK_LINES) + "\n"

HOW_TO_FILL = (
    "## Как заполнить карточку\n\n"
    "После открытия текста нормы: занести статьи в `article_or_clause`, ссылку на официальный текст в "
    "`primary_source_url`, тип нормы в `rule_type`, дату редакции открытого текста в `legal_state_at` и "
    "дату сверки в `verified_at`. Типы: `mandatory` — уставом изменить нельзя; `default` — действует, "
    "если устав не устанавливает иное; `optional` — устав вправе установить; `prohibition` — запрет; "
    "`exception` — исключение из общего правила. Текст нормы в карточку не копируется.\n"
)


def render(topic: str, title: str, questions: list[str]) -> str:
    slug_upper = topic.upper()
    items = "\n".join(f"- {q}" for q in questions)
    return (
        "---\n"
        f"rule_id: LLC.{slug_upper}\n"
        "jurisdiction: RU\n"
        "entity_type: LLC\n"
        f"topic: {topic}\n"
        "legal_state_at: null\n"
        "verified_at: null\n"
        "primary_source:\n"
        f"  - \"{ACT}\"\n"
        "primary_source_url: []\n"
        "article_or_clause: []\n"
        "rule_type: null\n"
        "amendment_risk: unknown\n"
        "verification_required: true\n"
        "---\n"
        f"# {title}\n\n"
        f"{POLICY}\n"
        "## Что искать в тексте нормы\n\n"
        f"{items}\n\n"
        f"{HOW_TO_FILL}"
    )


DEFAULT_TARGET = Path(__file__).resolve().parents[2] / "references" / "corporate-norm-cards" / "llc"


def generate(target: Path = DEFAULT_TARGET) -> int:
    """Создать недостающие скелеты; вернуть число созданных файлов."""
    target.mkdir(parents=True, exist_ok=True)
    created = 0
    for topic, (title, questions) in TOPICS.items():
        path = target / f"{cards.card_slug(topic)}.md"
        if path.exists():
            continue
        path.write_text(render(topic, title, questions), encoding="utf-8", newline="\n")
        created += 1
    return created


def _use_utf8_output() -> None:
    """Консоль Windows (cp1251/cp866) не кодирует «→»: переключить вывод на UTF-8, как в governance.py."""
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")


def main() -> int:
    _use_utf8_output()
    created = generate(DEFAULT_TARGET)
    print(f"создано карточек: {created} → {DEFAULT_TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
